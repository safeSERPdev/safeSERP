const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const manifest = JSON.parse(
  fs.readFileSync(path.join(root, "extension", "manifest.json"), "utf8")
);
const version = manifest.version;
if (!version) throw new Error("manifest.json missing version");

const publicDir = path.join(root, "frontend", "public");
const zipName = `safeserp-extension-${version}.zip`;
const zipPath = path.join(publicDir, zipName);
const extensionDir = path.join(root, "extension");

// Drop legacy unversioned zip and any other versioned builds (keep only current).
for (const file of fs.readdirSync(publicDir)) {
  if (
    file === "safeserp-extension.zip" ||
    /^safeserp-extension-\d+\.\d+\.\d+\.zip$/.test(file)
  ) {
    fs.unlinkSync(path.join(publicDir, file));
  }
}

// AMO rejects Windows backslash entry names (e.g. content\content.js).
// Build the zip with forward-slash paths via .NET ZipFile.
const extEsc = extensionDir.replace(/'/g, "''");
const zipEsc = zipPath.replace(/'/g, "''");
const ps = `
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
if (Test-Path -LiteralPath '${zipEsc}') { Remove-Item -LiteralPath '${zipEsc}' -Force }
$zip = [System.IO.Compression.ZipFile]::Open('${zipEsc}', 'Create')
try {
  $root = (Resolve-Path -LiteralPath '${extEsc}').Path.TrimEnd('\\')
  Get-ChildItem -LiteralPath $root -Recurse -File | ForEach-Object {
    $rel = $_.FullName.Substring($root.Length + 1).Replace('\\', '/')
    [void][System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
      $zip,
      $_.FullName,
      $rel,
      [System.IO.Compression.CompressionLevel]::Optimal
    )
  }
} finally {
  $zip.Dispose()
}
`;

execFileSync("powershell.exe", ["-NoProfile", "-Command", ps], {
  stdio: "inherit",
});

const versionModule =
  "/* auto-generated by scripts/pack-extension.js — do not edit */\n" +
  `export const EXTENSION_VERSION = ${JSON.stringify(version)};\n` +
  `export const EXTENSION_ZIP_NAME = ${JSON.stringify(zipName)};\n` +
  `export const EXTENSION_ZIP_URL = ${JSON.stringify("/" + zipName)};\n`;

fs.writeFileSync(
  path.join(root, "frontend", "src", "extensionVersion.js"),
  versionModule
);

console.log("Packed", zipName);
